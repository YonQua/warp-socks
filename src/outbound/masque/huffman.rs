/// 解码一段 Huffman 压缩字节，返回原始字节。
///
/// # Errors
/// 遇到非法码字、结尾非全 1 padding、或出现 EOS 符号时返回错误。
pub fn decode(buf: &[u8]) -> Result<Vec<u8>, &'static str> {
    let mut out = Vec::with_capacity(buf.len() * 2);
    let mut acc: u64 = 0;
    let mut nbits: u32 = 0;

    for &byte in buf {
        acc = (acc << 8) | u64::from(byte);
        nbits += 8;

        while let Some((sym, len)) = match_symbol(acc, nbits) {
            if sym == 256 {
                return Err("Huffman 流中出现 EOS 符号");
            }
            out.push(sym as u8);
            nbits -= len;
            acc &= (1u64 << nbits) - 1;
        }
    }

    // 结尾剩余位数必须 <8 且全为 1（EOS 前缀 padding，RFC 7541 §5.2）。
    if nbits >= 8 {
        return Err("Huffman 数据结尾前存在未解码的完整字节");
    }
    if nbits > 0 {
        let padding_mask = (1u64 << nbits) - 1;
        if acc & padding_mask != padding_mask {
            return Err("Huffman padding 不是全 1，数据可能损坏");
        }
    }
    Ok(out)
}

/// 用当前累积的 `nbits` 位（右对齐于 `acc`）尝试匹配一个完整码字。
/// 码表是前缀码，若某个长度 `len<=nbits` 的码字与 `acc` 高 `len` 位相等，
/// 该匹配即唯一合法解码（不会有更短或更长的码字同时匹配同一段前缀）。
fn match_symbol(acc: u64, nbits: u32) -> Option<(usize, u32)> {
    for (sym, &(code, len)) in TABLE.iter().enumerate() {
        let len = u32::from(len);
        if len <= nbits {
            let shift = nbits - len;
            let candidate = (acc >> shift) & ((1u64 << len) - 1);
            if candidate == u64::from(code) {
                return Some((sym, len));
            }
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    // 以下字节均截取自真实 MASQUE CONNECT 响应（见 outbound/masque/mod.rs 里
    // 对该响应的手工解析记录），不是构造出来的数据。
    #[test]
    fn decodes_cf_warp_colo_name() {
        let bytes = hex(b"24ab781d95ac43d07f");
        assert_eq!(decode(&bytes).unwrap(), b"cf-warp-colo");
    }

    #[test]
    fn decodes_lax_value() {
        let bytes = hex(b"cf0fe7");
        assert_eq!(decode(&bytes).unwrap(), b"LAX");
    }

    #[test]
    fn decodes_cf_warp_metal_name() {
        let bytes = hex(b"24ab781d95ad49523a3f");
        assert_eq!(decode(&bytes).unwrap(), b"cf-warp-metal");
    }

    #[test]
    fn rejects_eos_in_stream() {
        // 全 1 的一个字节不足以构成合法码字前缀，只会作为 padding 被接受；
        // 用超过一字节的全 1 制造出实际 EOS 完整码字（30 bit）来触发错误。
        let all_ones = [0xffu8; 4];
        assert!(decode(&all_ones).is_err());
    }

    fn hex(s: &[u8]) -> Vec<u8> {
        s.chunks(2)
            .map(|c| u8::from_str_radix(std::str::from_utf8(c).unwrap(), 16).unwrap())
            .collect()
    }
}
