}

verify_runtime_environment() {
  required_cmds="curl jq wg $WARP_RS_BIN"

  for required_cmd in $required_cmds; do
    command -v "$required_cmd" >/dev/null 2>&1 || fail_tunnel "缺少运行依赖: ${required_cmd}"
  done
}
