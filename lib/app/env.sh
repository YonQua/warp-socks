normalize_runtime_tuning() {
  REGISTER_RETRIES="$(sanitize_positive_int "$REGISTER_RETRIES" 2)"
  REGISTER_RETRY_DELAY="$(sanitize_nonnegative_int "$REGISTER_RETRY_DELAY" 2)"
